function baseTrade(
  partial: Partial<JournalTrade> & Pick<JournalTrade, "id" | "ticker" | "status" | "pnl">
): JournalTrade {
  return normalizeJournalTrade({
    assetClass: "Equities",
    direction: "Long",
    outcome: partial.pnl > 0 ? "Win" : partial.pnl < 0 ? "Loss" : "Breakeven",
    strategy: "Breakout",
    tags: ["Swing"],
    entryDate: "2026-07-01T09:30:00.000Z",
    exitDate: partial.status === "Active" ? "" : "2026-07-18T10:00:00.000Z",
    entryPrice: 100,
    exitPrice: partial.status === "Active" ? 0 : 105,
    quantity: 10,
    fees: 0,
    stopLoss: 95,
    profitTarget: 115,
    roi: partial.pnl > 0 ? 5 : -3,
    holdTimeHours: partial.status === "Active" ? 72 : 120,
    riskReward: "1:2",
    plannedRisk: 500,
    realizedRisk: partial.pnl < 0 ? Math.abs(partial.pnl) : 0,
    mindset: 3,
    notes: "",
    psychology: [],
    executions: [],
    screenshots: [],
    listingMarket: "IN_NSE",
    ...partial,
  });
}

